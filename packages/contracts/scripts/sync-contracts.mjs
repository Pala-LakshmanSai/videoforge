async function filesBelow(directory) {
  try {
    const entries = await readdir(directory, { withFileTypes: true });
    const nested = await Promise.all(
      entries.map(async (entry) => {
        const candidate = path.join(directory, entry.name);
        return entry.isDirectory() ? filesBelow(candidate) : [candidate];
      }),
    );
    return nested.flat();
  } catch (error) {
    if (error && error.code === "ENOENT") return [];
    throw error;
  }
}

const differences = [];
for (const [destination, expected] of expectedFiles) {
  let actual;
  try {
    actual = await readFile(destination);
  } catch (error) {
    if (error && error.code !== "ENOENT") throw error;
  }
  if (!actual || !actual.equals(expected)) {
    differences.push(`${actual ? "changed" : "missing"}: ${relativeToPackage(destination)}`);
    if (!checkOnly) {
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, expected);
    }
  }
}

const generatedRoot = path.join(packageRoot, "generated");
for (const existing of await filesBelow(generatedRoot)) {
  if (!expectedFiles.has(existing)) {
    differences.push(`stale: ${relativeToPackage(existing)}`);
    if (!checkOnly && (await stat(existing)).isFile()) await unlink(existing);
  }
}

if (checkOnly && differences.length > 0) {
  console.error("Canonical contract copies are out of sync:");
  for (const difference of differences) console.error(`- ${difference}`);
  process.exitCode = 1;
} else if (checkOnly) {
  console.log(`Contract sync check passed (${manifestEntries.length} canonical files).`);
} else {
  console.log(
    `Contract sync complete (${manifestEntries.length} canonical files, ${differences.length} updates).`,
  );
}
