const validIdentifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/u;
const propertyName = (value) => (validIdentifier.test(value) ? value : JSON.stringify(value));

function resolveJsonPointer(document, pointer) {
  if (pointer === "" || pointer === "#") return document;
  const fragment = pointer.startsWith("#") ? pointer.slice(1) : pointer;
  if (!fragment.startsWith("/")) throw new Error(`Unsupported JSON Schema pointer: ${pointer}`);
  return fragment
    .slice(1)
    .split("/")
    .map((part) => part.replaceAll("~1", "/").replaceAll("~0", "~"))
    .reduce((value, part) => value?.[part], document);
}

function resolveSchemaReference(reference, rootSchema) {
  if (reference.startsWith("#")) {
    const resolved = resolveJsonPointer(rootSchema, reference);
    if (resolved === undefined) throw new Error(`Unresolved local schema reference: ${reference}`);
    return { schema: resolved, rootSchema, key: `${rootSchema.$id}${reference}` };
  }

  const [schemaId, fragment = ""] = reference.split("#", 2);
  const referencedRoot = schemasById.get(schemaId);
  if (!referencedRoot) throw new Error(`Unresolved external schema reference: ${reference}`);
  const pointer = fragment ? `#${fragment}` : "#";
  const resolved = resolveJsonPointer(referencedRoot, pointer);
  if (resolved === undefined) throw new Error(`Unresolved external schema pointer: ${reference}`);
  return { schema: resolved, rootSchema: referencedRoot, key: reference };
}

function schemaType(schema, rootSchema, resolving = new Set()) {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  if (!schema || typeof schema !== "object") return "unknown";

  if (typeof schema.$ref === "string") {
    const resolved = resolveSchemaReference(schema.$ref, rootSchema);
    if (resolving.has(resolved.key)) return "unknown";
    const next = new Set(resolving);
    next.add(resolved.key);
    return schemaType(resolved.schema, resolved.rootSchema, next);
  }

  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum))
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf.map((entry) => `(${schemaType(entry, rootSchema, resolving)})`).join(" | ");
  }
  if (Array.isArray(schema.anyOf)) {
    return schema.anyOf.map((entry) => `(${schemaType(entry, rootSchema, resolving)})`).join(" | ");
  }
  if (Array.isArray(schema.type)) {
    return schema.type
      .map((type) => schemaType({ ...schema, type }, rootSchema, resolving))
      .join(" | ");
  }

  if (schema.type === "null") return "null";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "number" || schema.type === "integer") return "number";
  if (schema.type === "string") return "string";
  if (schema.type === "array" || schema.items) {
    return `readonly (${schemaType(schema.items ?? true, rootSchema, resolving)})[]`;
  }

  if (schema.type === "object" || schema.properties) {
    const conditionalBranches = (schema.allOf ?? []).filter(
      (entry) => entry?.if?.properties && entry?.then?.properties,
    );
    const discriminators = new Set(
      conditionalBranches.flatMap((entry) => Object.keys(entry.if.properties)),
    );
    if (conditionalBranches.length > 0 && discriminators.size === 1) {
      const [discriminator] = discriminators;
      const discriminatorSchema = schema.properties?.[discriminator];
      if (Array.isArray(discriminatorSchema?.enum)) {
        const conditionedProperties = new Set([
          discriminator,
          ...conditionalBranches.flatMap((entry) => Object.keys(entry.then.properties)),
        ]);
        const commonProperties = Object.fromEntries(
          Object.entries(schema.properties ?? {}).filter(
            ([name]) => !conditionedProperties.has(name),
          ),
        );
        const commonRequired = (schema.required ?? []).filter(
          (name) => !conditionedProperties.has(name),
        );
        const commonType = schemaType(
          {
            ...schema,
            allOf: undefined,
            properties: commonProperties,
            required: commonRequired,
          },
          rootSchema,
          resolving,
        );
        const variants = discriminatorSchema.enum.map((discriminatorValue) => {
          const matchingBranch = conditionalBranches.find(
            (entry) => entry.if.properties[discriminator]?.const === discriminatorValue,
          );
          const variantProperties = Object.fromEntries(
            [...conditionedProperties].map((name) => [
              name,
              name === discriminator
                ? { const: discriminatorValue }
                : (matchingBranch?.then.properties[name] ?? schema.properties[name]),
            ]),
          );
          const variantRequired = (schema.required ?? []).filter((name) =>
            conditionedProperties.has(name),
          );
          return schemaType(
            {
              type: "object",
              additionalProperties: false,
              properties: variantProperties,
              required: variantRequired,
            },
            rootSchema,
            resolving,
          );
        });
        return `(${commonType}) & (${variants.map((variant) => `(${variant})`).join(" | ")})`;
      }
    }

    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(
      ([name, propertySchema]) =>
        `readonly ${propertyName(name)}${required.has(name) ? "" : "?"}: ${schemaType(propertySchema, rootSchema, resolving)};`,
    );
    if (schema.additionalProperties === true) fields.push("readonly [property: string]: unknown;");
    if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
      fields.push(
        `readonly [property: string]: ${schemaType(schema.additionalProperties, rootSchema, resolving)};`,
      );
    }
    return `{ ${fields.join(" ")} }`;
  }

  if (Array.isArray(schema.allOf)) {
    const structuralEntries = schema.allOf.filter(
      (entry) => !entry.if && !entry.then && !entry.else,
    );
    if (structuralEntries.length > 0) {
      return structuralEntries
        .map((entry) => `(${schemaType(entry, rootSchema, resolving)})`)
        .join(" & ");
    }
  }

  return "unknown";
}

