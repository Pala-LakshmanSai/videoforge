import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, stat, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(packageRoot, "../..");
const evidenceRoot = path.join(repositoryRoot, "project-context/evidence");
const checkOnly = process.argv.includes("--check");

const schemaSpecs = [
  ["avatarProfileVersion", "avatar_profile_version.schema.json"],
  ["createProjectRequest", "create_project_request.schema.json"],
  ["imageStyleProfile", "image_style_profile.schema.json"],
  ["imageStyleAnalyzerOutput", "image_style_analyzer_output.schema.json"],
  ["projectRevisionConfig", "project_revision_config.schema.json"],
  ["timelinePlan", "timeline_plan.schema.json"],
  ["resolvedRenderManifest", "resolved_render_manifest.schema.json"],
  ["productionManifest", "production_manifest.schema.json"],
];

const fixtureFiles = [
  "avatar_profile_version.valid.json",
  "create_project_request.invalid.inline_avatar.json",
  "create_project_request.invalid.over_budget.json",
  "create_project_request.valid.json",
  "production_manifest.valid.json",
  "project_revision_config.invalid.compatibility_mismatch.json",
  "project_revision_config.valid.json",
  "resolved_render_manifest.invalid.avatar_profile_crop.json",
  "resolved_render_manifest.valid.json",
  "timeline_plan.valid.json",
];

const toPosix = (value) => value.split(path.sep).join("/");
const relativeToRepository = (value) => toPosix(path.relative(repositoryRoot, value));
const relativeToPackage = (value) => toPosix(path.relative(packageRoot, value));
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

const expectedFiles = new Map();
const manifestEntries = [];
const schemaDocuments = {};

async function addCanonicalCopy(source, destination) {
  const bytes = await readFile(source);
  expectedFiles.set(destination, bytes);
  manifestEntries.push({
    source: relativeToRepository(source),
    destination: relativeToPackage(destination),
    bytes: bytes.byteLength,
    sha256: `sha256:${sha256(bytes)}`,
  });
}

for (const [contractName, filename] of schemaSpecs) {
  const source = path.join(evidenceRoot, filename);
  const destination = path.join(packageRoot, "generated/schemas", filename);
  await addCanonicalCopy(source, destination);
  schemaDocuments[contractName] = JSON.parse(await readFile(source, "utf8"));
}

for (const filename of fixtureFiles) {
  await addCanonicalCopy(
    path.join(evidenceRoot, "fixtures", filename),
    path.join(packageRoot, "generated/fixtures", filename),
  );
}

await addCanonicalCopy(
  path.join(evidenceRoot, "default_image_style_v1.json"),
  path.join(packageRoot, "generated/fixtures/default_image_style_v1.json"),
);

const manifest = {
  generated_by: "packages/contracts/scripts/sync-contracts.mjs",
  canonical_root: "project-context/evidence",
  files: manifestEntries,
};
expectedFiles.set(
  path.join(packageRoot, "generated/manifest.json"),
  Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`),
);

const typescriptModule =
  `// Generated by scripts/sync-contracts.mjs. Do not edit.\n` +
  `export const canonicalSchemaDocuments = ${JSON.stringify(schemaDocuments, null, 2)} as const;\n`;
expectedFiles.set(
  path.join(packageRoot, "generated/schema-documents.ts"),
  Buffer.from(typescriptModule),
);

const embeddedSchemas = JSON.stringify(JSON.stringify(schemaDocuments));
const pythonModule =
  `# Generated by scripts/sync-contracts.mjs. Do not edit.\n` +
  `from __future__ import annotations\n\n` +
  `import json\n\n` +
  `SCHEMA_DOCUMENTS: dict[str, dict[str, object]] = json.loads(${embeddedSchemas})\n`;
expectedFiles.set(
  path.join(packageRoot, "python/videoforge_contracts/_schema_documents.py"),
  Buffer.from(pythonModule),
);

async function filesBelow(directory) {
  try {
    const entries = await readdir(directory, { withFileTypes: true });
    const nested = await Promise.all(
      entries.map(async (entry) => {
        const candidate = path.join(directory, entry.name);
        return entry.isDirectory() ? filesBelow(candidate) : [candidate];
      }),
    );
    return nested.flat();
  } catch (error) {
    if (error && error.code === "ENOENT") return [];
    throw error;
  }
}

const differences = [];
for (const [destination, expected] of expectedFiles) {
  let actual;
  try {
    actual = await readFile(destination);
  } catch (error) {
    if (error && error.code !== "ENOENT") throw error;
  }
  if (!actual || !actual.equals(expected)) {
    differences.push(`${actual ? "changed" : "missing"}: ${relativeToPackage(destination)}`);
    if (!checkOnly) {
      await mkdir(path.dirname(destination), { recursive: true });
      await writeFile(destination, expected);
    }
  }
}

const generatedRoot = path.join(packageRoot, "generated");
for (const existing of await filesBelow(generatedRoot)) {
  if (!expectedFiles.has(existing)) {
    differences.push(`stale: ${relativeToPackage(existing)}`);
    if (!checkOnly && (await stat(existing)).isFile()) await unlink(existing);
  }
}

if (checkOnly && differences.length > 0) {
  console.error("Canonical contract copies are out of sync:");
  for (const difference of differences) console.error(`- ${difference}`);
  process.exitCode = 1;
} else if (checkOnly) {
  console.log(`Contract sync check passed (${manifestEntries.length} canonical files).`);
} else {
  console.log(
    `Contract sync complete (${manifestEntries.length} canonical files, ${differences.length} updates).`,
  );
}
